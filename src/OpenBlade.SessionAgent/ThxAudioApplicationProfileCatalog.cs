    internal static IReadOnlyList<ThxAudioApplicationProfile> AvailableProfiles(
        IReadOnlyList<string> nativePresetIds)
    {
        var available = nativePresetIds.ToHashSet(StringComparer.Ordinal);
        return [.. Profiles
            .OrderBy(pair => pair.Key, StringComparer.Ordinal)
            .Select(pair => new ThxAudioApplicationProfile(
                pair.Key,
                pair.Value.ImmersivePresetId is not null
                    && available.Contains(pair.Value.ImmersivePresetId),
                pair.Value.CompetitivePresetId is not null
                    && available.Contains(pair.Value.CompetitivePresetId)))
            .Where(profile => profile.SupportsImmersive || profile.SupportsCompetitive)];
    }

    internal static bool TryResolve(
        string executableName,
        ThxAudioApplicationMode mode,
        out string nativePresetId)
    {
        nativePresetId = string.Empty;
        if (!Profiles.TryGetValue(executableName, out ThxNativeApplicationProfile? profile))
        {
            return false;
        }

        string? candidate = mode switch
        {
            ThxAudioApplicationMode.Immersive => profile.ImmersivePresetId,
            ThxAudioApplicationMode.Competitive => profile.CompetitivePresetId,
            _ => null,
        };
        if (candidate is null)
        {
            return false;
        }
        nativePresetId = candidate;
        return true;
    }
